export type PicKey = keyof typeof PICS;

const cache = new Map<PicKey, string>();

/** Готовая SVG-разметка схемы (с кэшем — схемы статичны). */
export function picMarkup(key: PicKey): string {
  let s = cache.get(key);
  if (!s) {
    s = picSvg(PICS[key] as PicDef);
    cache.set(key, s);
  }
  return s;
}
